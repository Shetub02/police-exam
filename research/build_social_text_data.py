def marker(line):
    m = re.match(r"^([1-4])(?:\s*[.,:)]\s*|\s+)(.*)", line)
    if m:
        return int(m.group(1)), m.group(2)
    return None


def parse_block(number, block):
    hits = [(i, *marker(line)) for i, line in enumerate(block) if marker(line)]
    run = None
    for i in range(len(hits) - 3):
        if [x[1] for x in hits[i:i + 4]] == [1, 2, 3, 4]:
            run = hits[i:i + 4]
            break
    if not run:
        return {"number": number, "block": block, "hits": hits}
    prompt = clean(" ".join(block[:run[0][0]]))
    prompt = re.sub(rf"^.*?\b(?:{number}|[0-9]{{1,3}})\s*[.,)]?\s*", "", prompt, count=1).strip()
    choices = []
    for i, (line_index, _, first) in enumerate(run):
        end = run[i + 1][0] if i < 3 else len(block)
        choices.append(clean(" ".join([first, *block[line_index + 1:end]])))
    return {"number": number, "question": prompt, "choices": choices}


